package claude

import (
	"bufio"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/project-kikkuli/yamnaya/internal/core"
)

func TestChannelSupervisionUsesOneNativeEventAndIndependentActionReceipts(t *testing.T) {
	for _, size := range []int{1, 16} {
		t.Run(fmt.Sprintf("actions_%d", size), func(t *testing.T) { testChannelBatch(t, size) })
	}
}

func testChannelBatch(t *testing.T, size int) {
	dir, err := os.MkdirTemp("/tmp", "ym-channel-test-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "s")
	in, send := io.Pipe()
	out, receive := io.Pipe()
	defer send.Close()
	defer out.Close()
	defer receive.Close()
	acknowledged, completed := map[string]int{}, map[string]string{}
	done := make(chan error, 1)
	go func() {
		done <- ServeChannel(context.Background(), path, "native", in, receive, ChannelCallbacks{Accept: func(id string) error { acknowledged[id]++; return nil }, Complete: func(id, result string) error { completed[id] = result; return nil }})
	}()
	type output struct {
		message map[string]json.RawMessage
		err     error
	}
	messages := make(chan output, 64)
	go func() {
		defer close(messages)
		scanner := bufio.NewScanner(out)
		for scanner.Scan() {
			var message map[string]json.RawMessage
			err := json.Unmarshal(scanner.Bytes(), &message)
			messages <- output{message: message, err: err}
			if err != nil {
				return
			}
		}
		if err := scanner.Err(); err != nil {
			messages <- output{err: err}
		}
	}()
	next := 0
	request := func(method string, params any) {
		t.Helper()
		next++
		if err := json.NewEncoder(send).Encode(map[string]any{"jsonrpc": "2.0", "id": next, "method": method, "params": params}); err != nil {
			t.Fatal(err)
		}
	}
	read := func() map[string]json.RawMessage {
		t.Helper()
		value, ok := <-messages
		if !ok {
			t.Fatal("MCP output ended")
		}
		if value.err != nil {
			t.Fatal(value.err)
		}
		return value.message
	}
	response := func() map[string]json.RawMessage {
		t.Helper()
		value := read()
		if len(value["method"]) > 0 {
			t.Fatalf("unexpected duplicate native event: %s", value["params"])
		}
		return value
	}
	pending := func() []channelAction {
		t.Helper()
		request("tools/call", map[string]any{"name": "pending", "arguments": map[string]any{}})
		value := response()
		var result struct {
			Content []struct {
				Text string `json:"text"`
			} `json:"content"`
		}
		if err := json.Unmarshal(value["result"], &result); err != nil || len(result.Content) != 1 {
			t.Fatalf("pending tool response: %s %v", value["result"], err)
		}
		var actions []channelAction
		if err := json.Unmarshal([]byte(result.Content[0].Text), &actions); err != nil {
			t.Fatal(err)
		}
		return actions
	}
	request("initialize", map[string]string{"protocolVersion": "2025-03-26"})
	init := response()
	var capabilities struct {
		Capabilities struct {
			Experimental map[string]json.RawMessage `json:"experimental"`
		} `json:"capabilities"`
	}
	if err := json.Unmarshal(init["result"], &capabilities); err != nil {
		t.Fatal(err)
	}
	if _, ok := capabilities.Capabilities.Experimental["claude/channel"]; !ok {
		t.Fatal("native channel capability missing")
	}
	request("notifications/initialized", nil)
	request("ping", nil)
	response()
	adapter := &Adapter{ChannelSocket: func(core.Session) string { return path }}
	ids := make([]string, size)
	var parts []string
	for i := range ids {
		ids[i] = fmt.Sprintf("%032x", i+1)
		header := "review"
		if size > 1 {
			header = "attempt 1, review"
		}
		parts = append(parts, fmt.Sprintf("Yamnaya supervisor action %s (%s), generated by manager; this is not a message from the human owner.\nReview result %d", ids[i], header, i))
	}
	text := strings.Join(parts, "\n\n")
	submit := func(content string) {
		t.Helper()
		if err := adapter.Message(core.Session{ID: "native"}, content, false); !errors.Is(err, core.ErrSubmissionUncertain) {
			t.Fatalf("native pipe write counted as acknowledgement: %v", err)
		}
	}
	event := func(content string, wantIDs []string, wantAttempt int) {
		t.Helper()
		value := read()
		var method string
		json.Unmarshal(value["method"], &method)
		if method != "notifications/claude/channel" {
			t.Fatalf("wrong native event: %s", value["method"])
		}
		var params struct {
			Content string            `json:"content"`
			Meta    map[string]string `json:"meta"`
		}
		if err := json.Unmarshal(value["params"], &params); err != nil {
			t.Fatal(err)
		}
		if params.Content != content || params.Meta["action_id"] != wantIDs[0] || params.Meta["action_ids"] != strings.Join(wantIDs, ",") || params.Meta["session_id"] != "native" {
			t.Fatalf("bad channel provenance: %+v", params)
		}
		var attempts map[string]int
		if err := json.Unmarshal([]byte(params.Meta["action_attempts"]), &attempts); err != nil {
			t.Fatal(err)
		}
		for _, id := range wantIDs {
			if attempt, ok := attempts[id]; !ok || attempt != wantAttempt {
				t.Fatalf("wrong attempt provenance: %+v", attempts)
			}
		}
		if _, ok := value["message"]; ok {
			t.Fatal("user message envelope emitted")
		}
	}
	submit(text)
	initialAttempt := 0
	if size > 1 {
		initialAttempt = 1
	}
	event(text, ids, initialAttempt)
	registered := pending()
	if len(registered) != size {
		t.Fatalf("batch lost individual actions: %+v", registered)
	}
	total := 0
	for _, action := range registered {
		total += len(action.Content)
		if !strings.HasPrefix(action.Content, "Yamnaya supervisor action "+action.ID+" ") || strings.Count(action.Content, "Yamnaya supervisor action ") != 1 {
			t.Fatalf("pending repeats unrelated batch context: %+v", action)
		}
	}
	if total != len(text) {
		t.Fatalf("pending content expands batch: %d bytes, original %d", total, len(text))
	}
	submit(text)
	request("ping", nil)
	response()
	for _, id := range ids {
		request("tools/call", map[string]any{"name": "acknowledge", "arguments": map[string]string{"action_id": id}})
		response()
		if acknowledged[id] != 1 {
			t.Fatalf("wrong acknowledgement for %s: %v", id, acknowledged)
		}
		request("tools/call", map[string]any{"name": "complete", "arguments": map[string]string{"action_id": id, "result": "landed"}})
		response()
		if completed[id] != "landed" {
			t.Fatalf("wrong completion: %v", completed)
		}
	}
	submit(text)
	if actions := pending(); len(actions) != 0 {
		t.Fatalf("socket replay revived completed actions: %+v", actions)
	}
	retry := fmt.Sprintf("Yamnaya supervisor action %s (attempt 2, review), generated by manager.\nExplicitly retry review", ids[0])
	submit(retry)
	event(retry, ids[:1], 2)
	stale := fmt.Sprintf("Yamnaya supervisor action %s (review), generated by manager.\nStale legacy attempt", ids[0])
	submit(stale)
	registered = pending()
	if len(registered) != 1 || registered[0].Attempt != 2 || registered[0].Content != retry {
		t.Fatalf("stale delivery replaced newer attempt: %+v", registered)
	}
	mixed := fmt.Sprintf("Yamnaya supervisor action %s (attempt 3, review), generated by manager.\nNewest retry\n\n%s", ids[0], retry)
	submit(mixed)
	event(mixed, ids[:1], 3)
	submit(mixed)
	registered = pending()
	if len(registered) != 1 || registered[0].Attempt != 3 || registered[0].Content != strings.SplitN(mixed, "\n\n", 2)[0]+"\n\n" {
		t.Fatalf("mixed-attempt batch lost newest attempt: %+v", registered)
	}
	send.Close()
	if err := <-done; err != nil {
		t.Fatal(err)
	}
}
