package claude

import (
	"bufio"
	"context"
	"encoding/json"
	"errors"
	"io"
	"os"
	"path/filepath"
	"testing"

	"github.com/project-kikkuli/yamnaya/internal/core"
)

func TestChannelSupervisionUsesNativeEventsAndRequiresSessionAcknowledgement(t *testing.T) {
	dir, err := os.MkdirTemp("/tmp", "ym-channel-test-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "s")
	in, send := io.Pipe()
	out, receive := io.Pipe()
	defer send.Close()
	defer out.Close()
	acknowledged := ""
	completed := ""
	done := make(chan error, 1)
	go func() {
		done <- ServeChannel(context.Background(), path, "native", in, receive, ChannelCallbacks{Accept: func(id string) error { acknowledged = id; return nil }, Complete: func(id, result string) error { completed = id + ":" + result; return nil }})
	}()
	scanner := bufio.NewScanner(out)
	request := func(id int, method string, params any) {
		t.Helper()
		if err := json.NewEncoder(send).Encode(map[string]any{"jsonrpc": "2.0", "id": id, "method": method, "params": params}); err != nil {
			t.Fatal(err)
		}
	}
	read := func() map[string]json.RawMessage {
		t.Helper()
		if !scanner.Scan() {
			t.Fatal("MCP output ended")
		}
		var message map[string]json.RawMessage
		if err := json.Unmarshal(scanner.Bytes(), &message); err != nil {
			t.Fatal(err)
		}
		return message
	}
	request(1, "initialize", map[string]string{"protocolVersion": "2025-03-26"})
	init := read()
	var result struct {
		Capabilities struct {
			Experimental map[string]json.RawMessage `json:"experimental"`
		} `json:"capabilities"`
	}
	if err := json.Unmarshal(init["result"], &result); err != nil {
		t.Fatal(err)
	}
	if _, ok := result.Capabilities.Experimental["claude/channel"]; !ok {
		t.Fatal("native channel capability missing")
	}
	request(2, "notifications/initialized", nil)
	request(3, "ping", nil)
	read()
	adapter := &Adapter{ChannelSocket: func(core.Session) string { return path }}
	actionID := "0123456789abcdef0123456789abcdef"
	text := "Yamnaya supervisor action " + actionID + " (review), generated by manager; this is not a message from the human owner.\nReview the result"
	sent := make(chan error, 1)
	go func() { sent <- adapter.Message(core.Session{ID: "native"}, text, false) }()
	event := read()
	var method string
	json.Unmarshal(event["method"], &method)
	if method != "notifications/claude/channel" {
		t.Fatalf("wrong native event: %s", event["method"])
	}
	var params struct {
		Content string            `json:"content"`
		Meta    map[string]string `json:"meta"`
	}
	if err := json.Unmarshal(event["params"], &params); err != nil {
		t.Fatal(err)
	}
	if params.Content != text || params.Meta["action_id"] != actionID || params.Meta["session_id"] != "native" {
		t.Fatalf("bad channel provenance: %+v", params)
	}
	if _, ok := event["message"]; ok {
		t.Fatal("user message envelope emitted")
	}
	if err := <-sent; !errors.Is(err, core.ErrSubmissionUncertain) {
		t.Fatalf("native pipe write counted as acknowledgement: %v", err)
	}
	request(4, "tools/call", map[string]any{"name": "acknowledge", "arguments": map[string]string{"action_id": actionID}})
	read()
	if acknowledged != actionID {
		t.Fatalf("wrong acknowledgement: %q", acknowledged)
	}
	request(5, "tools/call", map[string]any{"name": "complete", "arguments": map[string]string{"action_id": actionID, "result": "landed"}})
	read()
	if completed != actionID+":landed" {
		t.Fatalf("wrong completion: %q", completed)
	}
	send.Close()
	if err := <-done; err != nil {
		t.Fatal(err)
	}
}
