const nativePeerFixtureKey = "ci-local-mock-not-a-provider-key"

// This exercises the real CLI and peer sockets; every model response is deterministic simulation.
func TestRealClaudePeerTransportWithSimulatedModel(t *testing.T) {
	if os.Getenv("YM_REAL_CLAUDE_PEER_FIXTURE") != "1" {
		t.Skip("requires the explicit isolated GitHub CI fixture")
	}
	if os.Getenv("GITHUB_ACTIONS") != "true" || os.Geteuid() == 0 {
		t.Fatal("native fixture requires GitHub CI and a non-root user")
	}
	interfaces, err := net.Interfaces()
	if err != nil {
		t.Fatal(err)
	}
	for _, iface := range interfaces {
		if iface.Flags&net.FlagLoopback == 0 {
			t.Fatalf("fixture has a non-loopback interface: %s", iface.Name)
		}
	}
	binary := os.Getenv("YM_REAL_CLAUDE_BIN")
	if binary != "/fixture/claude" {
		t.Fatal("native fixture binary must be the pinned read-only CI artifact")
	}
	file, err := os.Open(binary)
	if err != nil {
		t.Fatal(err)
	}
	var magic [4]byte
	_, err = io.ReadFull(file, magic[:])
	file.Close()
	if err != nil || !bytes.Equal(magic[:], []byte{0x7f, 'E', 'L', 'F'}) {
		t.Fatal("fixture requires the pinned real Linux native binary")
	}
	t.Log("REAL Claude CLI 2.1.314 / SIMULATED localhost model; transport evidence only, no real model behavior or provider billing")
	for _, policy := range []string{"accept", "hold", "refuse"} {
		t.Run(policy, func(t *testing.T) {
			ctx, cancel := context.WithTimeout(context.Background(), 40*time.Second)
			defer cancel()
			model := newNativePeerModel(t)
			native := startNativePeer(t, ctx, binary, policy, model.server.URL)
			native.waitResult(t, ctx)
			a := New()
			a.Dir = native.config
			a.ReceiptWait = 2 * time.Second
			a.SendTimeout = 2 * time.Second
			var st state
			waitNativePeer(t, ctx, func() bool {
				var ok bool
				st, ok = a.state(native.cmd.Process.Pid)
				if !ok || st.SessionID != native.id || st.PeerProtocol != peerProtocol || st.MessagingSocket == "" {
					return false
				}
				info, e := os.Stat(st.MessagingSocket)
				return e == nil && info.Mode()&os.ModeSocket != 0
			}, native.diagnostics)
			info, err := os.Stat(st.MessagingSocket)
			if err != nil {
				t.Fatal(err)
			}
			private := info.Mode().Perm()&0077 == 0
			if !private {
				parent, e := os.Stat(filepath.Dir(st.MessagingSocket))
				private = e == nil && parent.Mode().Perm()&0077 == 0
			}
			if !private {
				t.Fatalf("native peer socket has no private filesystem boundary: %s", info.Mode())
			}
			before := model.count()
			nonce := "YM_REAL_NATIVE_PEER_" + policy
			action := "Yamnaya supervisor action 0123456789abcdef0123456789abcdef (attempt 1, directive), generated by CI fixture; this is not a message from the human owner.\n" + nonce
			target := core.Session{ID: native.id, PID: native.cmd.Process.Pid, Harness: Name, Cwd: native.cwd}
			sendErr := a.Message(target, action, false)
			switch policy {
			case "accept":
				if !errors.Is(sendErr, core.ErrSubmissionUncertain) {
					t.Fatalf("accepted peer delivery must await action acknowledgement: %v", sendErr)
				}
				native.waitResult(t, ctx)
				if got := model.count(); got != before+1 {
					t.Fatalf("native delivery produced %d model requests, want one; %s", got-before, native.diagnostics())
				}
				text := model.lastText(nonce)
				if !strings.Contains(text, nonce) || !strings.Contains(text, "cross-session-message") || !strings.Contains(text, "YM") {
					t.Fatalf("native request lost peer content/provenance: %.1800s", text)
				}
				for _, forbidden := range []string{"from-mode=", `from-name="owner"`, `from-name="The owner"`, `from-name="user"`} {
					if strings.Contains(text, forbidden) {
						t.Fatalf("native request granted sender mode or owner provenance: %.1800s", text)
					}
				}
				// Permission denial faults the real native socket before submission, without substituting a server or receipt.
				faultBefore := model.count()
				if err = os.Chmod(st.MessagingSocket, 0); err != nil {
					t.Fatal(err)
				}
				faultErr := a.Message(target, action+"_UNREACHABLE", false)
				restoreErr := os.Chmod(st.MessagingSocket, info.Mode().Perm())
				if restoreErr != nil {
					t.Fatal(restoreErr)
				}
				if faultErr == nil || errors.Is(faultErr, core.ErrSubmissionUncertain) {
					t.Fatalf("pre-write transport denial was not definite: %v", faultErr)
				}
				model.assertQuiet(t, faultBefore)
			case "hold", "refuse":
				var receipt NotReadError
				want := map[string]string{"hold": "held", "refuse": "refused"}[policy]
				if !errors.As(sendErr, &receipt) || receipt.Status != want {
					t.Fatalf("real native %s receipt missing: %v; %s", want, sendErr, native.diagnostics())
				}
				if errors.Is(sendErr, core.ErrSubmissionUncertain) != (policy == "hold") {
					t.Fatalf("native receipt lost certainty distinction: %v", sendErr)
				}
				model.assertQuiet(t, before)
			}
			model.assertValid(t)
		})
	}
}

type nativePeerModel struct {
	server   *httptest.Server
	mu       sync.Mutex
	requests [][]byte
	failures []string
	calls    int
}

func newNativePeerModel(t *testing.T) *nativePeerModel {
	t.Helper()
	m := &nativePeerModel{}
	m.server = httptest.NewServer(http.HandlerFunc(m.serve))
	t.Cleanup(m.server.Close)
	return m
}

func (m *nativePeerModel) serve(w http.ResponseWriter, r *http.Request) {
	m.mu.Lock()
	m.calls++
	calls := m.calls
	m.mu.Unlock()
	fail := func(message string) {
		m.mu.Lock()
		m.failures = append(m.failures, message)
		m.mu.Unlock()
		http.Error(w, message, http.StatusBadRequest)
	}
	if calls > 24 {
		fail("mock request limit exceeded")
		return
	}
	if r.Method != http.MethodPost || r.Header.Get("X-Api-Key") != nativePeerFixtureKey || r.Header.Get("Authorization") != "" {
		fail("unexpected method or credential source")
		return
	}
	raw, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 8<<20))
	if err != nil {
		fail("mock request exceeded limit")
		return
	}
	if r.URL.Path == "/v1/messages/count_tokens" {
		w.Header().Set("Content-Type", "application/json")
		io.WriteString(w, `{"input_tokens":0}`)
		return
	}
	if r.URL.Path != "/v1/messages" {
		fail("unexpected mock path: " + r.URL.Path)
		return
	}
	var request struct {
		Model  string
		Stream bool
	}
	if err = json.Unmarshal(raw, &request); err != nil {
		fail("invalid Messages JSON")
		return
	}
	m.mu.Lock()
	m.requests = append(m.requests, append([]byte(nil), raw...))
	sequence := len(m.requests)
	m.mu.Unlock()
	usage := map[string]int{"input_tokens": 0, "output_tokens": 0}
	message := map[string]any{"id": fmt.Sprintf("msg_simulated_ci_%d", sequence), "type": "message", "role": "assistant", "model": request.Model, "content": []any{}, "stop_reason": nil, "stop_sequence": nil, "usage": usage}
	if !request.Stream {
		message["content"] = []any{map[string]string{"type": "text", "text": "SIMULATED_MODEL_OUTPUT: fixture turn complete"}}
		message["stop_reason"] = "end_turn"
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(message)
		return
	}
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	event := func(kind string, data any) {
		raw, _ := json.Marshal(data)
		fmt.Fprintf(w, "event: %s\ndata: %s\n\n", kind, raw)
		if f, ok := w.(http.Flusher); ok {
			f.Flush()
		}
	}
	event("message_start", map[string]any{"type": "message_start", "message": message})
	event("content_block_start", map[string]any{"type": "content_block_start", "index": 0, "content_block": map[string]string{"type": "text", "text": ""}})
	event("content_block_delta", map[string]any{"type": "content_block_delta", "index": 0, "delta": map[string]string{"type": "text_delta", "text": "SIMULATED_MODEL_OUTPUT: fixture turn complete"}})
	event("content_block_stop", map[string]any{"type": "content_block_stop", "index": 0})
	event("message_delta", map[string]any{"type": "message_delta", "delta": map[string]any{"stop_reason": "end_turn", "stop_sequence": nil}, "usage": map[string]int{"output_tokens": 0}})
	event("message_stop", map[string]string{"type": "message_stop"})
}

func (m *nativePeerModel) count() int { m.mu.Lock(); defer m.mu.Unlock(); return len(m.requests) }
func (m *nativePeerModel) lastText(marker string) string {
	m.mu.Lock()
	defer m.mu.Unlock()
	if len(m.requests) == 0 {
		return ""
	}
	var request struct{ Messages []json.RawMessage }
	json.Unmarshal(m.requests[len(m.requests)-1], &request)
	var out []string
	var visit func(any)
	visit = func(v any) {
		switch x := v.(type) {
		case string:
			out = append(out, x)
		case []any:
			for _, value := range x {
				visit(value)
			}
		case map[string]any:
			for _, value := range x {
				visit(value)
			}
		}
	}
	var selected []string
	for _, raw := range request.Messages {
		var message any
		if json.Unmarshal(raw, &message) != nil {
			continue
		}
		out = nil
		visit(message)
		text := strings.Join(out, "\n")
		if strings.Contains(text, marker) {
			selected = append(selected, text)
		}
	}
	return strings.Join(selected, "\n")
}
func (m *nativePeerModel) assertQuiet(t *testing.T, before int) {
	t.Helper()
	deadline := time.Now().Add(time.Second)
	for time.Now().Before(deadline) {
		if m.count() != before {
			t.Fatal("held/refused/unreachable peer message triggered a model request")
		}
		time.Sleep(25 * time.Millisecond)
	}
}
func (m *nativePeerModel) assertValid(t *testing.T) {
	t.Helper()
	m.mu.Lock()
	defer m.mu.Unlock()
	if len(m.failures) > 0 {
		t.Fatalf("mock rejected unexpected traffic: %v", m.failures)
	}
}

type nativePeerLog struct {
	mu   sync.Mutex
	data []byte
}

func (l *nativePeerLog) Write(p []byte) (int, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	l.data = append(l.data, p...)
	if len(l.data) > 32<<10 {
		l.data = l.data[len(l.data)-(32<<10):]
	}
	return len(p), nil
}
func (l *nativePeerLog) String() string { l.mu.Lock(); defer l.mu.Unlock(); return string(l.data) }

type nativePeerProcess struct {
	cmd             *exec.Cmd
	stdin           io.WriteCloser
	config, cwd, id string
	results         chan string
	exited          chan struct{}
	logs            nativePeerLog
}

func startNativePeer(t *testing.T, ctx context.Context, binary, policy, baseURL string) *nativePeerProcess {
	t.Helper()
	base := t.TempDir()
	n := &nativePeerProcess{config: filepath.Join(base, "claude"), cwd: filepath.Join(base, "work"), id: map[string]string{"accept": "12345678-1234-4234-8234-123456789ab1", "hold": "12345678-1234-4234-8234-123456789ab2", "refuse": "12345678-1234-4234-8234-123456789ab3"}[policy], results: make(chan string, 8), exited: make(chan struct{})}
	paths := map[string]string{"HOME": filepath.Join(base, "home"), "TMPDIR": filepath.Join(base, "tmp"), "CLAUDE_CONFIG_DIR": n.config, "CODEX_HOME": filepath.Join(base, "codex"), "XDG_CONFIG_HOME": filepath.Join(base, "xdg-config"), "XDG_CACHE_HOME": filepath.Join(base, "xdg-cache"), "XDG_DATA_HOME": filepath.Join(base, "xdg-data")}
	env := []string{"PATH=/usr/bin:/bin", "LANG=C.UTF-8", "TERM=dumb", "CI=true", "ANTHROPIC_API_KEY=" + nativePeerFixtureKey, "ANTHROPIC_BASE_URL=" + baseURL, "NO_PROXY=127.0.0.1,localhost", "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1", "DISABLE_TELEMETRY=1", "DISABLE_ERROR_REPORTING=1", "DISABLE_AUTOUPDATER=1", "DISABLE_GROWTHBOOK=1", "CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL=1", "DISABLE_PROMPT_CACHING=1"}
	for key, path := range paths {
		if err := os.MkdirAll(path, 0700); err != nil {
			t.Fatal(err)
		}
		env = append(env, key+"="+path)
	}
	if err := os.MkdirAll(n.cwd, 0700); err != nil {
		t.Fatal(err)
	}
	version := exec.CommandContext(ctx, binary, "--version")
	version.Env = env
	version.Dir = n.cwd
	out, err := version.CombinedOutput()
	fields := strings.Fields(string(out))
	if err != nil || len(fields) == 0 || fields[0] != "2.1.314" {
		t.Fatalf("wrong native CLI version: %s %v", out, err)
	}
	settings, _ := json.Marshal(map[string]string{"crossSessionInbound": policy})
	n.cmd = exec.CommandContext(ctx, binary, "-p", "--input-format", "stream-json", "--output-format", "stream-json", "--verbose", "--session-id", n.id, "--name", "ym-native-ci-"+policy, "--model", "sonnet", "--tools", "", "--strict-mcp-config", "--mcp-config", `{"mcpServers":{}}`, "--setting-sources", "", "--settings", string(settings), "--max-turns", "2")
	n.cmd.Dir, n.cmd.Env = n.cwd, env
	n.cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	n.cmd.Stderr = &n.logs
	stdout, err := n.cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	n.stdin, err = n.cmd.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	if err = n.cmd.Start(); err != nil {
		t.Fatal(err)
	}
	go func() {
		scanner := bufio.NewScanner(stdout)
		scanner.Buffer(make([]byte, 4096), 2<<20)
		for scanner.Scan() {
			line := append([]byte(nil), scanner.Bytes()...)
			n.logs.Write(append(line, '\n'))
			var event struct {
				Type    string
				IsError bool `json:"is_error"`
				Result  string
			}
			if json.Unmarshal(line, &event) == nil && event.Type == "result" {
				result := ""
				if event.IsError {
					result = event.Result
					if result == "" {
						result = "native result reported is_error"
					}
				}
				select {
				case n.results <- result:
				default:
				}
			}
		}
	}()
	go func() {
		err := n.cmd.Wait()
		if err != nil {
			fmt.Fprintln(&n.logs, "native process:", err)
		}
		close(n.exited)
	}()
	t.Cleanup(func() {
		select {
		case <-n.exited:
			return
		default:
		}
		syscall.Kill(-n.cmd.Process.Pid, syscall.SIGTERM)
		n.stdin.Close()
		select {
		case <-n.exited:
		case <-time.After(3 * time.Second):
			syscall.Kill(-n.cmd.Process.Pid, syscall.SIGKILL)
			select {
			case <-n.exited:
			case <-time.After(time.Second):
				t.Error("native fixture process did not terminate")
			}
		}
	})
	input := map[string]any{"type": "user", "session_id": n.id, "parent_tool_use_id": nil, "message": map[string]string{"role": "user", "content": "Initialize this transport-only CI fixture; model responses are simulated."}}
	if err = json.NewEncoder(n.stdin).Encode(input); err != nil {
		t.Fatal(err)
	}
	return n
}
func (n *nativePeerProcess) waitResult(t *testing.T, ctx context.Context) {
	t.Helper()
	select {
	case result := <-n.results:
		if result != "" {
			t.Fatalf("native turn failed: %s; %s", result, n.diagnostics())
		}
	case <-n.exited:
		t.Fatalf("native session exited: %s", n.diagnostics())
	case <-ctx.Done():
		t.Fatalf("native turn timed out: %s", n.diagnostics())
	}
}
func (n *nativePeerProcess) diagnostics() string {
	s := n.logs.String()
	if len(s) > 8000 {
		return s[len(s)-8000:]
	}
	return s
}
func waitNativePeer(t *testing.T, ctx context.Context, ready func() bool, diagnostics func() string) {
	t.Helper()
	ticker := time.NewTicker(25 * time.Millisecond)
	defer ticker.Stop()
	for {
		if ready() {
			return
		}
		select {
		case <-ticker.C:
		case <-ctx.Done():
			t.Fatalf("native peer state unavailable: %s", diagnostics())
		}
	}
}
